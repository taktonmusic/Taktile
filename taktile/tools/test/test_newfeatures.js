/* Shift + Menu = mixer, Copy + own track button = duplicate the track, LFO tab, chord stays after leaving the mode, record length counted from your first note */
const { ctx, run } = require('./harness.js');
let bad = 0; const ok = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) bad++; };
const T = n => { for (let i = 0; i < n; i++) ctx.tick(); };
const cc = (n, v) => ctx.onMidiMessageInternal([0xB0, n, v]);
ctx.init && ctx.init(); T(300); run('splashT0 = 0');
run('chosen[0] = 1; askKind = -1; selectTrack(0); setKind(0, 0); selectTrack(0); askKind = -1; view = 0'); T(10);
cc(49, 127); cc(50, 127); cc(50, 0); cc(49, 0); T(3);
ok(run('view') === 20, 'Shift + Menu opens the mixer (view ' + run('view') + ')');
cc(49, 127); cc(50, 127); cc(50, 0); cc(49, 0); T(3);
ok(run('view') !== 20, 'Shift + Menu again leaves it');
run('view = 0; steps[ed[0]][0][0] = [1, 100, 0, 0, 0, 0, 0, 0]; steps[ed[0]][0][4] = [1, 100, 3, 0, 0, 0, 0, 0]; selectTrack(0)'); T(3);
cc(60, 127); ctx.onMidiMessageInternal([0x90 + 0, 0, 0]); cc(43, 127); cc(43, 0); cc(60, 0); T(3);
ok(run('trackAnyNotes(1)') === true, 'Copy + the selected track button copied the track to the next empty track');
ok(run('sel') === 1, 'and selected it');
run('selectTrack(0); tabEnter(53)'); T(2);
ok(run('VIEW_ITEMS[53].length') === 6 && run('VIEW_ITEMS[53][0][0]') === 'l1t', 'LFO tab has its 6 knobs');
run('editParam("pad", "l1t", 7, 0); editParam("pad", "l1t", 7, 0)'); T(2);
ok(run('Math.round(pads[0][PI.l1t])') === 2, 'LFO 1 target changes (' + run('pads[0][PI.l1t]') + ')');
run('askKind = -1'); cc(3, 127); T(2); ok(run('VIEW_ITEMS[53][0][0]') === 'l2t', 'jog click = next LFO');
run('selectTrack(0); view = 0; topModes[0] = 4; chordReconcile()'); T(2);
ok(run('pads[0][PI.mfx]') === 2, 'chord mode sets the chord effect');
run('topModes[0] = 0; chordReconcile()'); T(2);
ok(run('pads[0][PI.mfx]') === 2, 'leaving chord mode with notes keeps the chord effect');
run('selectTrack(5); for (let c = 0; c < NPAT; c++) for (const l of lanesOf(5)) { steps[c][l] = steps[c][l].map(() => [0, 100, 0, 0]); }; topModes[5] = 4; chordReconcile(); topModes[5] = 0; chordReconcile()'); T(2);
ok(run('pads[5][PI.mfx]') !== 2, 'an empty track gets its old effect back');
run('selectTrack(2); lens[2] = 32; growTrk[2] = true; growG0[2] = 0; growP0[2] = 10; growMax[2] = 1; gs = 27; recStopLen()');
ok(run('lens[2]') === 16, 'stopped 16 steps after the first note: the clip is 16 steps (' + run('lens[2]') + ')');
run('lens[2] = 32; growTrk[2] = true; growG0[2] = 0; growP0[2] = 0; growMax[2] = 20; gs = 12; recStopLen()');
ok(run('lens[2]') === 32, 'notes in the second bar keep it at 32');
run('askKind = -1; guideOpenAt(3)'); T(3); run('drawCore()');
ok(run('guideI') === 3, 'a guide topic opens');
cc(14, 1); cc(14, 1); T(1); ok(run('guideP') === 1, 'jog = next page');
cc(51, 127); T(1); ok(run('guideI') === -1, 'Back closes the guide');
ok(run("MENU_GROUPS.some(g => g[0] === 'GUIDE' && g[1].length === 10)"), 'GUIDE group in the menu with 10 topics');
console.log(bad ? bad + ' FAILED' : 'all ok'); process.exit(bad ? 1 : 0);
