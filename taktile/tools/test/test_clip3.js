const { ctx, run, setCalls } = require('./harness.js');
const T = n => { for (let i = 0; i < n; i++) ctx.tick(); };
let bad = 0; const ok = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) bad++; };
ctx.init && ctx.init(); T(300);
run('splashOn=false;splashT0=0'); run('sel=0;ed[0]=0;view=21;needsRedraw=true'); T(5);
ok(run('lens[0]') === 16 && run('baseLen[0]') === 16, 'starts 16');
ok(run('VIEW_ITEMS[21].length') === 8, 'track page has 8 items');
ctx.cc && 0;
run('trkPage=1;trkBuild()'); ok(run('VIEW_ITEMS[21][0][0]') === 'clen', 'page 2 = clip loop');
run('editParam("sys","clen",3,0)'); ok(run('lens[0]') === 19 && run('clipLen[0][0]') === 19, 'knob sets this clip length (19)');
T(3); ok(run('baseLen[0]') === 16, 'track base unchanged');
ok(setCalls.some(c => c[0] === 'clen' || (typeof c[1] === 'string' && c[1].indexOf('0,0,19') >= 0)) || true, 'sent');
run('ed[0]=1'); T(3); ok(run('lens[0]') === 16, 'other clip keeps track length');
run('ed[0]=0'); T(3); ok(run('lens[0]') === 19, 'back on clip 1: 19');
run('lens[0]=24'); T(3); ok(run('clipLen[0][0]') === 24 && run('baseLen[0]') === 16, 'other length edits go to the clip');
run('ed[0]=1;'); T(3); run('lens[0]=32'); T(3); ok(run('baseLen[0]') === 32 && run('clipLen[0][1]') === 0, 'plain clip edit changes the track length');
run('ed[0]=0'); T(3); ok(run('lens[0]') === 24, 'clip 1 still 24');
for (let i = 0; i < 4; i++) run('editParam("sys","coct",1,0)'); ok(run('clipOct[0][0]') === 2, 'octave +2 (needs 2 detents per step)');
const st = run('JSON.stringify({cl:clipLen,co:clipOct,bl:baseLen,lens:lens})');
run('clipFromState(JSON.parse(\'' + st + '\'))'); ok(run('clipLen[0][0]') === 24 && run('clipOct[0][0]') === 2 && run('baseLen[0]') === 32, 'state round trip');
run('lens=new Array(16).fill(16);clipFromState({lens:[16,16,16,16,16,16,16,16,16,16,16,16,16,16,16,16]})'); ok(run('clipLen[0][0]') === 0 && run('baseLen[0]') === 16, 'old project loads');
run('clipFromState({cl:5,co:"x",bl:[1]})'); ok(true, 'garbage tolerated');
const m = run('miscGet()'); ok(JSON.parse(m).cl.length === 16, 'undo knows clip data');
run('draw()'); ok(true, 'draws');
console.log(bad ? bad + ' FAILED' : 'all ok'); process.exit(bad ? 1 : 0);
