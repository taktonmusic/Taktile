const { ctx, run, cc } = require('./harness.js');
const T = n => { for (let i = 0; i < n; i++) ctx.tick(); };
let bad = 0; const ok = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) bad++; };
ctx.init && ctx.init(); T(600);
run('splashOn=false;splashT0=0;chosen.fill(1);askKind=-1;view=0;playing=false;needsRedraw=true'); T(3);
run('for (let t=0;t<8;t++) for (let c=0;c<8;c++) steps[c][lanesOf(t)[0]][0]=[1,100,0,0,0,0,0,0]'); T(2);
run('openHub(); hubSel[16]=HUBS[16][1].findIndex(t=>t[1]===31)'); T(2);
cc(run('CC.JOGCLICK'), 127); cc(run('CC.JOGCLICK'), 0); T(5);
run('songTick()');
ok(run('view') === 31 && run('songOn'), 'song page, song on');
cc(run('CC.SHIFT'), 127); ctx.onMidiMessageInternal([0x90, run('PAD_FIRST') + 2, 100]); ctx.onMidiMessageInternal([0x80, run('PAD_FIRST') + 2, 0]); cc(run('CC.SHIFT'), 0); T(3);
ok(run('view') === 0, 'Shift+pad opens the track');
run('songTick()'); ok(run('songOn') === true, 'song keeps running in the track page');
run('draw()');
cc(run('CC.BACK'), 127); cc(run('CC.BACK'), 0); T(3);
ok(run('view') === 31 && run('songOn'), 'Back = song page again, still song mode');
cc(run('CC.BACK'), 127); cc(run('CC.BACK'), 0); T(3); run('songTick()');
ok(run('songOn') === false && run('view') !== 31, 'Back in song page = song mode over');
console.log(bad ? 'FAILED' : 'all ok'); process.exit(bad ? 1 : 0);
